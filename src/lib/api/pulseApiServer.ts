export type MomentRow = {
  id: string
  childId: string
  childName: string
  title: string
  desc: string
  domain: string
  source: 'voice' | 'photo' | 'cctv'
  status: MomentStatus
  observationId: string
  createdAt: string
  confirmedAt?: string
  deliveredAt?: string
  telegramSimulated?: boolean
  tag?: string
  mediaUrls?: string[]
  rawRef?: string
}

type ObservationRow = HermesObservationIngest & {
  id: string
  childId: string
  createdAt: string
}

type PaymentRow = {
  id: string
  invoiceId: string
  parentId: string
  amount: number
  method: string
  journalNo: string
  isConfirmed: boolean
  createdAt: string
}

type InvoiceDraft = {
  invoiceNo: string
  childId: string
  dueDate: string
  totalAmt: number
  status: 'draft' | 'issued'
  isAutoGenerated: true
}

type Listener = () => void

const observations = new Map<string, ObservationRow>()
const moments = new Map<string, MomentRow>()
const payments = new Map<string, PaymentRow>()
const autoInvoices: InvoiceDraft[] = []
const listeners = new Set<Listener>()

/** Bump on mutate so useSyncExternalStore getSnapshot can return stable refs. */
let storeVersion = 0
const listCache = new Map<string, { version: number; value: MomentRow[] }>()

function notify() {
  storeVersion += 1
  listeners.forEach((l) => l())
}

function cachedMoments(key: string, compute: () => MomentRow[]): MomentRow[] {
  const hit = listCache.get(key)
  if (hit && hit.version === storeVersion) return hit.value
  const value = compute()
  listCache.set(key, { version: storeVersion, value })
  return value
}

export function subscribePulseStore(listener: Listener): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

function uid(prefix: string) {
  return `${prefix}_${crypto.randomUUID()}`
}

function resolveChildId(name: string, childId?: string) {
  if (childId) return childId
  const key = name.toLowerCase()
  if (key.includes('kinley')) return 'c1'
  if (key.includes('tashi')) return 'c2'
  if (key.includes('pema')) return 'c3'
  if (key.includes('yeshi')) return 'c4'
  return 'c1'
}

function parentSafeCopy(data: HermesObservationIngest, childName: string) {
  const first = childName.split(' ')[0] ?? childName
  return {
    title: data.parentSafeTitle ?? `${first}'s classroom moment`,
    desc:
      data.parentSafeDesc ??
      `${first} showed progress in ${data.domain}. ${data.milestone}`,
  }
}

/** POST /api/observations/from-hermes → pending_facilitator moment */
export function postObservationFromHermes(body: unknown) {
  const parsed = HermesObservationIngestSchema.safeParse(body)
  if (!parsed.success) {
    return { ok: false as const, status: 400, error: parsed.error.flatten() }
  }
  const data = parsed.data
  const childId = resolveChildId(data.childName, data.childId)
  const now = new Date().toISOString()
  const { title, desc } = parentSafeCopy(data, data.childName)
  const observation: ObservationRow = {
    ...data,
    id: uid('obs'),
    childId,
    createdAt: now,
  }
  const moment: MomentRow = {
    id: uid('mom'),
    childId,
    childName: data.childName,
    title,
    desc,
    domain: data.domain,
    source: data.source,
    status: 'pending_facilitator',
    observationId: observation.id,
    createdAt: now,
    tag: data.source === 'voice' ? 'Voice' : data.source === 'photo' ? 'Photo' : 'CCTV',
    mediaUrls: data.mediaUrls,
    rawRef: data.rawRef,
  }
  observations.set(observation.id, observation)
  moments.set(moment.id, moment)
  notify()
  return { ok: true as const, status: 201, data: { observation, moment } }
}

/**
 * POST /api/moments/:id/confirm
 * facilitator → pending_director (Director ELDS gate)
 * owner → delivered + telegramSimulated
 */
export function postConfirmMoment(id: string, body: unknown = {}) {
  const parsed = ConfirmMomentSchema.safeParse(body)
  if (!parsed.success) {
    return { ok: false as const, status: 400, error: parsed.error.flatten() }
  }
  const moment = moments.get(id)
  if (!moment) return { ok: false as const, status: 404, error: 'Moment not found' }

  const now = new Date().toISOString()
  const role = parsed.data.role

  if (role === 'facilitator') {
    if (moment.status !== 'pending_facilitator') {
      return {
        ok: false as const,
        status: 409,
        error: `Moment is ${moment.status}; facilitator confirm expects pending_facilitator`,
      }
    }
    const updated: MomentRow = {
      ...moment,
      status: 'pending_director',
      confirmedAt: now,
    }
    moments.set(id, updated)
    notify()
    return { ok: true as const, status: 200, data: updated }
  }

  if (moment.status === 'delivered') {
    return { ok: true as const, status: 200, data: moment }
  }
  if (
    moment.status !== 'pending_director' &&
    moment.status !== 'pending_facilitator'
  ) {
    return {
      ok: false as const,
      status: 409,
      error: `Cannot owner-confirm moment in status ${moment.status}`,
    }
  }

  const updated: MomentRow = {
    ...moment,
    status: 'delivered',
    confirmedAt: moment.confirmedAt ?? now,
    deliveredAt: now,
    telegramSimulated: true,
  }
  moments.set(id, updated)
  notify()
  return { ok: true as const, status: 200, data: updated }
}

export function postAutoInvoiceRun(body: unknown) {
  const parsed = AutoInvoiceRunSchema.safeParse(body)
  if (!parsed.success) {
    return { ok: false as const, status: 400, error: parsed.error.flatten() }
  }
  const { asOf, dryRun, leadDays } = parsed.data
  const asOfDate = new Date(asOf.includes('T') ? asOf : `${asOf}T00:00:00`)
  const due = new Date(asOfDate)
  due.setDate(due.getDate() + leadDays)

  const drafts: InvoiceDraft[] = [
    {
      invoiceNo: `WSH-${due.getFullYear()}-${String(autoInvoices.length + 163).padStart(6, '0')}`,
      childId: 'c1',
      dueDate: due.toISOString().slice(0, 10),
      totalAmt: 1000,
      status: dryRun ? 'draft' : 'issued',
      isAutoGenerated: true,
    },
    {
      invoiceNo: `WSH-${due.getFullYear()}-${String(autoInvoices.length + 164).padStart(6, '0')}`,
      childId: 'c2',
      dueDate: due.toISOString().slice(0, 10),
      totalAmt: 7000,
      status: dryRun ? 'draft' : 'issued',
      isAutoGenerated: true,
    },
  ]

  if (!dryRun) autoInvoices.push(...drafts)

  return {
    ok: true as const,
    status: 200,
    data: {
      asOf: asOfDate.toISOString().slice(0, 10),
      leadDays,
      dryRun,
      created: drafts.length,
      invoices: drafts,
      note: 'Tuition discounts never apply to ancillary fees (Uniform, Extended time, Potty).',
    },
  }
}

export function postPaymentReport(body: unknown) {
  const parsed = PaymentReportSchema.safeParse(body)
  if (!parsed.success) {
    return { ok: false as const, status: 400, error: parsed.error.flatten() }
  }
  const row: PaymentRow = {
    id: uid('pay'),
    ...parsed.data,
    isConfirmed: false,
    createdAt: new Date().toISOString(),
  }
  payments.set(row.id, row)
  notify()
  return { ok: true as const, status: 201, data: row }
}

/** Moments awaiting Director ELDS / Hermes confirmation */
export function listPendingDirectorMoments() {
  return cachedMoments('pending_director', () =>
    Array.from(moments.values())
      .filter((m) => m.status === 'pending_director')
      .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1)),
  )
}

/** @deprecated use listPendingDirectorMoments */
export function listPendingMoments() {
  return listPendingDirectorMoments()
}

/** Child-scoped parent moments — delivered only */
export function listParentMomentsForChild(childId: string) {
  return cachedMoments(`parent:${childId}`, () =>
    Array.from(moments.values())
      .filter((m) => m.childId === childId && m.status === 'delivered')
      .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1)),
  )
}

/** Delivered photo/video moments for child profile Photos tab. */
export function listParentMediaMomentsForChild(childId: string) {
  return cachedMoments(`parent-media:${childId}`, () =>
    listParentMomentsForChild(childId).filter((m) => (m.mediaUrls?.length ?? 0) > 0),
  )
}

/** Delivered moments for many children (teacher classroom wall). */
export function listDeliveredMomentsForChildren(childIds: string[]) {
  const key = `classroom:${[...childIds].sort().join(',')}`
  return cachedMoments(key, () => {
    const allow = new Set(childIds)
    return Array.from(moments.values())
      .filter((m) => allow.has(m.childId) && m.status === 'delivered')
      .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1))
  })
}

/** Director center-wide delivered feed. */
export function listAllDeliveredMoments() {
  return cachedMoments('center-delivered', () =>
    Array.from(moments.values())
      .filter((m) => m.status === 'delivered')
      .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1)),
  )
}

export function listPaymentReports() {
  return Array.from(payments.values())
}

